// Single source of truth for the in-app Sources panel (src/ui/SourcesPanel.ts, key G) and the per-place citations
// (src/app/placeSources.ts). `npm run check:refs` (scripts/check-refs.mjs) keeps it in sync with the docs: every
// author–year citation in README.md and docs/{ring-physics,data-sources,ARCHITECTURE}.md must resolve to an entry here,
// and every entry must be cited somewhere (docs, src/ code comments or placeSources.ts);
// `npm run check:refs -- --online` re-checks every DOI against Crossref / DataCite and every arXiv id.
//
// Adding a reference: give it an id (first-author surname + year, + a / b where the docs use letters), the
// metadata exactly as the publisher's record (Crossref for DOIs), what in the simulator uses it, its topics, and
// `verified` / `verifiedBy` (where the metadata were checked; never invent a DOI or page number — mark unverifiable
// entries `verified: false` with a `note`). Data products and software carry their licence.
//
// No imports: Node imports this file directly (type stripping) for the check script.

export type RefType = 'paper' | 'book' | 'thesis' | 'conference abstract' | 'dataset' | 'catalog' | 'software';

