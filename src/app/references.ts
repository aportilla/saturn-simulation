const BY_ID = new Map(REFERENCES.map((r) => [r.id, r]));

export function findReference(id: string): Reference | undefined {
  return BY_ID.get(id);
}

export function topicLabel(t: Topic): string {
  for (const [k, label] of TOPICS) if (k === t) return label;
  return t;
}

function surname(a: string): string {
  const i = a.indexOf(',');
  return i < 0 ? a : a.slice(0, i);
}

/** "Spitale & Porco 2010", "Iess et al. 2019", "Hapke 1984", or the entry's own short label. */
export function shortCite(r: Reference): string {
  if (r.short) return r.short;
  const y = `${r.year}${r.suffix ?? ''}`;
  if (r.etAl || r.authors.length > 2) return `${surname(r.authors[0])} et al. ${y}`;
  if (r.authors.length === 2) return `${surname(r.authors[0])} & ${surname(r.authors[1])} ${y}`;
  return `${surname(r.authors[0])} ${y}`;
}

/** Author list for the full citation: up to three authors, then "et al.". */
export function authorList(r: Reference): string {
  const a = r.authors;
  if (r.etAl) return `${a.join(', ')}, et al.`;
  if (a.length <= 1) return a[0] ?? '';
  return `${a.slice(0, -1).join(', ')} & ${a[a.length - 1]}`;
}

/** Primary link: DOI, else the landing page, else arXiv / ADS. */
export function primaryUrl(r: Reference): string | null {
  if (r.doi) return `https://doi.org/${r.doi}`;
  if (r.url) return r.url;
  if (r.arxiv) return `https://arxiv.org/abs/${r.arxiv}`;
  if (r.ads) return `https://ui.adsabs.harvard.edu/abs/${encodeURIComponent(r.ads)}`;
  return null;
}
