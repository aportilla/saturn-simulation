export type Topic = (typeof TOPICS)[number][0];

export interface Reference {
  /** stable key, e.g. 'spitale2010' (placeSources.ts and the panel's links use it) */
  id: string;
  type: RefType;
  /** 'Surname, I. I.': every author up to three; `etAl` when there are more */
  authors: string[];
  etAl?: boolean;
  year: number;
  /** letter the docs use to tell same-author, same-year works apart (Hedman et al. 2007a / 2007b) */
  suffix?: string;
  title: string;
  /** journal (abbreviated), "in <book> (eds.), publisher", archive or publisher */
  venue: string;
  volume?: string;
  /** page range or article number */
  pages?: string;
  doi?: string;
  arxiv?: string;
  /** NASA ADS bibcode */
  ads?: string;
  /** landing page (data archive, publisher, repository) when there is no DOI, or in addition to it */
  url?: string;
  topics: Topic[];
  /** what in the simulator uses it */
  usedFor: string;
  /** data products and software: licence / terms of use */
  licence?: string;
  /** metadata checked against an authoritative record (see verifiedBy) */
  verified: boolean;
  /** where the metadata were checked */
  verifiedBy: string;
  note?: string;
  /** strings that identify this entry in docs and code besides its author–year form (data set ids, product names) */
  cite?: string[];
  /** compact label for citation lines (default: "Surname et al. 2010" / "Surname & Other 2010" / "Surname 2010") */
  short?: string;
}

